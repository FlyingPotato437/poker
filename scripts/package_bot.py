"""LEGACY RESEARCH packaging. For Nov 6 uploads use scripts/official.py.

This historical single-file format does not implement the official explicit-memory
interface and embedded models can exceed the 1 MB agent.py limit. Its smoke test
is not an official upload check.

Bundle runtime + tables + tuned params + mock adapter into one research file.

    python scripts/package_bot.py --bundle bundles/day.nlb --params params/day.json --out dist/bot.py
    python scripts/package_bot.py --variant plo4 --out dist/bot.py          # heuristic, no tables
    python scripts/package_bot.py ... --sidecar                             # tables as a separate file

The smoke test imports the packaged file in a clean interpreter (-I, numpy hidden too
unless --allow-numpy) and plays a few SNGs against the zoo, so a broken package is
caught before it is submitted.
"""
import argparse
import base64
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIMIT_MB = 100

SMOKE = r"""
import importlib.util, os, random, sys, time
sys.path.insert(0, {root!r})
spec = importlib.util.spec_from_file_location("submitted_bot", {path!r})
t0 = time.perf_counter()
mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
load = time.perf_counter() - t0
from nolimit.engine import SNG
from nolimit.zoo import ZOO
T = mod._tables()
worst = 0.0
for g in range(4):
    agents = [mod.make_core(seed=g), mod.make_core(seed=g + 99)] + [ZOO[k](T, seed=g) for k in ("tag", "shover", "nit", "lag", "station", "timeout")]
    sng = SNG(T.v, agents, rng=random.Random(g)); sng.run()
    assert sum(sng.errors[:2]) == 0, "packaged bot raised during play"
    worst = max(worst, sng.timing[0].max, sng.timing[1].max)
print(f"smoke ok: variant {{T.v.name}}, tables {{type(T).__name__}}, numpy {{mod.np is not None}}, "
      f"import {{load:.2f}}s, worst decision {{worst:.3f}} ms")
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bundle", help="table bundle; omit for heuristic tables")
    ap.add_argument("--variant", default="nlhe", help="preset or variant JSON file for heuristic tables (no bundle)")
    ap.add_argument("--params", help="tuned params JSON")
    ap.add_argument("--adapter", default=os.path.join(ROOT, "adapter_template.py"))
    ap.add_argument("--out", default=os.path.join(ROOT, "dist", "bot.py"))
    ap.add_argument("--sidecar", action="store_true", help="ship the bundle as a file next to bot.py")
    ap.add_argument("--allow-numpy", action="store_true", help="let the smoke test use numpy")
    ap.add_argument("--pure-python", action="store_true",
                    help="never use numpy in the submitted bot (if numpy on their host shows latency spikes)")
    ap.add_argument("--no-smoke", action="store_true")
    args = ap.parse_args()

    with open(os.path.join(ROOT, "nolimit", "runtime.py")) as fh:
        runtime = fh.read()
    with open(args.adapter) as fh:
        adapter = "".join(line for line in fh if "PACKAGE: strip" not in line)
    params = {}
    if args.params:
        with open(args.params) as fh:
            params = json.load(fh)
    if args.pure_python:      # after the __future__ import, which must stay first
        fut = "from __future__ import annotations\n"
        assert fut in runtime
        runtime = runtime.replace(fut, fut + "import os\nos.environ['NOLIMIT_NO_NUMPY'] = '1'   # --pure-python\n", 1)
    parts = [runtime, "\n\n# ==== generated by scripts/package_bot.py ====\n",
             f"_PARAMS = {json.dumps(params, sort_keys=True)}\n"]
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    if args.bundle and args.sidecar:
        side = os.path.join(os.path.dirname(os.path.abspath(args.out)), "tables.nlb")
        shutil.copyfile(args.bundle, side)
        parts.append(f"_BUNDLE_FILE = {os.path.basename(side)!r}\n")
    elif args.bundle:
        with open(args.bundle, "rb") as fh:
            parts.append(f"_BUNDLE_B64 = {base64.b64encode(fh.read()).decode()!r}\n")
    else:
        variant = args.variant
        if variant.endswith(".json"):     # a variant that is not a preset: embed its rules
            with open(variant) as fh:
                variant = json.dumps(json.load(fh), separators=(",", ":"))
        parts.append(f"os.environ.setdefault('NOLIMIT_VARIANT', {variant!r})\n")
    parts.append("\n" + adapter)
    with open(args.out, "w") as fh:
        fh.write("".join(parts))
    size = os.path.getsize(args.out) / 1e6
    if args.sidecar and args.bundle:
        size += os.path.getsize(side) / 1e6
    flag = "  <-- OVER THE 100 MB LIMIT" if size > LIMIT_MB else ""
    print(f"wrote {args.out} ({size:.1f} MB total){flag}")
    if args.no_smoke:
        return
    env = dict(os.environ)
    if not args.allow_numpy:
        env["NOLIMIT_NO_NUMPY"] = "1"
    res = subprocess.run([sys.executable, "-c", SMOKE.format(root=ROOT, path=os.path.abspath(args.out))],
                         env=env, capture_output=True, text=True)
    print(res.stdout.strip() or res.stderr.strip())
    if res.returncode:
        sys.exit("smoke test FAILED")


if __name__ == "__main__":
    main()
