class Rec:
    def __init__(self, inner, keep): self.i, self.k = inner, keep
    def new_table(self, s, n): self.i.new_table(s, n)
    def observe(self, e): self.i.observe(e)
    def act(self, o):
        self.k.append(Obs(**{k: (list(getattr(o, k)) if isinstance(getattr(o, k), (list, tuple)) else getattr(o, k)) for k in Obs.__slots__}))
        return self.i.act(o)
