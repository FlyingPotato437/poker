"""Freeze the submission files: copy them read-only under frozen/<tag>/ with a hash manifest.

    python scripts/freeze.py --tag rc1                 # copy dist/ + dist/fallback/, write MANIFEST
    python scripts/freeze.py --tag rc1 --verify        # re-hash, fail on any change

The manifest records, per file, the sha256 of the whole file and of its parts (runtime,
params, embedded tables, adapter) and names the bundles/*.nlb and params/*.json it was built
from, so a test run can prove it played the frozen bytes. Day-of packaging swaps only the
adapter: split_package()/with_adapter() rebuild a file with another adapter and check that
everything above the adapter is unchanged.
"""
import argparse
import base64
import glob
import hashlib
import json
import os
import shutil
import stat
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARK = "\n\n# ==== generated by scripts/package_bot.py ====\n"


def sha(data):
    return hashlib.sha256(data.encode() if isinstance(data, str) else data).hexdigest()


def split_package(text):
    """Packaged file -> (runtime, generated block, adapter). The generated block is the
    _PARAMS line plus one tables line (_BUNDLE_B64, _BUNDLE_FILE or NOLIMIT_VARIANT)."""
    i = text.index(MARK)
    j = text.index("\n", i + len(MARK))            # end of the _PARAMS line
    j = text.index("\n", j + 1) + 1                # end of the tables line
    return text[:i], text[i:j], text[j:]


def strip_adapter(path):
    with open(path) as fh:
        return "".join(line for line in fh if "PACKAGE: strip" not in line)


def with_adapter(path, adapter_path):
    """The frozen file at `path` with its adapter replaced, as package_bot.py would build it."""
    with open(path) as fh:
        runtime, gen, _ = split_package(fh.read())
    return runtime + gen + "\n" + strip_adapter(adapter_path)


def describe(path):
    with open(path) as fh:
        text = fh.read()
    runtime, gen, adapter = split_package(text)
    params_line, tables_line = gen[len(MARK):].splitlines()[:2]
    params = json.loads(params_line[len("_PARAMS = "):])
    info = {"sha256": sha(text), "bytes": len(text.encode()), "runtime_sha256": sha(runtime),
            "params_sha256": sha(json.dumps(params, sort_keys=True)), "adapter_sha256": sha(adapter),
            "pure_python": "# --pure-python" in runtime}
    info["params_from"] = sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, "params", "*.json"))
                                 if json.load(open(p)) == params)
    if tables_line.startswith("_BUNDLE_B64 = "):
        blob = base64.b64decode(tables_line[len("_BUNDLE_B64 = "):].strip().strip("'\""))
        info["bundle_sha256"] = sha(blob)
        info["bundle_from"] = sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, "bundles", "*.nlb"))
                                     if os.path.getsize(p) == len(blob) and sha(open(p, "rb").read()) == sha(blob))
    else:
        info["tables"] = tables_line
    tmpl = strip_adapter(os.path.join(ROOT, "adapter_template.py"))
    info["adapter"] = "adapter_template.py" if adapter == "\n" + tmpl else "other"
    return info


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--src", default=os.path.join(ROOT, "dist"))
    ap.add_argument("--files", nargs="+", help="freeze these files instead of <src>/*_bot.py + <src>/fallback/")
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()
    out = os.path.join(ROOT, "frozen", args.tag)
    man_path = os.path.join(out, "MANIFEST.json")

    if args.verify:
        with open(man_path) as fh:
            man = json.load(fh)
        bad = [rel for rel, info in man["files"].items()
               if sha(open(os.path.join(out, rel), "rb").read()) != info["sha256"]]
        print(f"{len(man['files']) - len(bad)}/{len(man['files'])} frozen files match the manifest")
        sys.exit(f"CHANGED: {bad}" if bad else 0)

    if os.path.exists(out):
        sys.exit(f"{out} exists: frozen tags are never overwritten, pick a new --tag")
    if args.files:
        files = [os.path.abspath(f) for f in args.files]
        args.src = os.path.dirname(os.path.commonpath(files)) if len(files) == 1 else os.path.commonpath(files)
    else:
        files = sorted(glob.glob(os.path.join(args.src, "*_bot.py")) + glob.glob(os.path.join(args.src, "fallback", "*_bot.py")))
    man = {"tag": args.tag, "runtime_py_sha256": sha(open(os.path.join(ROOT, "nolimit", "runtime.py"), "rb").read()),
           "files": {}}
    for f in files:
        rel = os.path.relpath(f, args.src)
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(f, dst)
        os.chmod(dst, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
        man["files"][rel] = describe(dst)
        d = man["files"][rel]
        print(f"{rel:<34}{d['bytes'] / 1e6:>6.1f} MB  {d['sha256'][:12]}  params {d['params_from']}  "
              f"bundle {d.get('bundle_from', d.get('tables'))}  adapter {d['adapter']}")
    with open(man_path, "w") as fh:
        json.dump(man, fh, indent=1, sort_keys=True)
    os.chmod(man_path, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
    print(f"wrote {man_path}")


if __name__ == "__main__":
    main()
